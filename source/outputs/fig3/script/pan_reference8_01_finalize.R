suppressPackageStartupMessages(library(data.table))
write_utf8 <- function(text, path) {
  con <- file(path, open = "wb")
  on.exit(close(con), add = TRUE)
  writeBin(charToRaw(text), con)
}

OUT_ROOT <- "E:/micro_output/fig3/MP_FUN_PTG02/pan_disease_allcells_v3/reference8"
coverage_file <- file.path(OUT_ROOT, "tables/FUN8_cell_coverage_audit.csv")
registry_file <- file.path(OUT_ROOT, "tables/FUN8_T1_only_registry.csv")
score_file <- file.path(OUT_ROOT, "data/FUN8_UCell_scores_allcells.rds")
if (!all(file.exists(c(coverage_file, registry_file, score_file)))) stop("阶段A评分输出不完整，未执行收尾")

coverage <- fread(coverage_file)
registry <- fread(registry_file)
scores <- readRDS(score_file)
score_cols <- setdiff(names(scores), "CellID")
pan_n <- coverage[metric == "formal_pan14_cells", as.integer(value)]
scored_n <- coverage[metric == "FUN8_scored_cells", as.integer(value)]
finite_n <- coverage[metric == "FUN8_finite_cells", as.integer(value)]
expected_n <- coverage[metric == "pan14_expected_reference", as.integer(value)]
if (nrow(scores) != scored_n || anyDuplicated(scores$CellID) || any(!is.finite(as.matrix(scores[, ..score_cols])))) stop("评分输出收尾审计失败")
if (pan_n != 365563L || scored_n != pan_n || finite_n != pan_n) stop("pan14评分覆盖未达到完整范围")

interpretation <- paste0(
  "# FUN8 T1-only全细胞评分\n\n",
  "## 分析目的\n",
  "在正式对象的完整pan14细胞范围内，按冻结的原始8个T1功能签名重新计算UCell评分，作为当前规划阶段A的基础结果。\n\n",
  "## 输入与范围\n",
  "- 正式对象：`E:/micro_output/v3_dims16/objects/merged_obj.rds`\n",
  "- pan14细胞：", format(pan_n, big.mark = ","), "个；参考核对值：", format(expected_n, big.mark = ","), "个\n",
  "- RNA assay既有data layer；未重算PCA、Harmony、UMAP、聚类或轨迹。\n\n",
  "## 方法\n",
  "使用`UCell::ScoreSignatures_UCell`，maxRank=1500、ties.method=average、chunk.size=1000、ncores=1、SerialParam、force.gc=TRUE；外部分块大小20,000，seed=42。未施加sample或sample×cluster门槛，未使用轨迹抽样细胞限制评分。\n\n",
  "## 结果\n",
  "8个签名、", nrow(registry), "条签名基因记录、", uniqueN(registry$gene), "个唯一请求基因完成RNA data layer映射；评分覆盖", format(scored_n, big.mark = ","), "/", format(pan_n, big.mark = ","), "个pan14细胞（1.000000），有限值覆盖", format(finite_n / scored_n, digits = 6), "。\n\n",
  "## 限制与边界\n",
  "本结果只完成T1-only 8功能评分和审计，不替代既有12FUN、12MP、PTG或轨迹结果，也不启动规划中的B–F阶段。"
)
interpretation_file <- file.path(OUT_ROOT, paste0(intToUtf8(c(35299L, 35835L)), ".md"))
write_utf8(interpretation, interpretation_file)
run_log <- file.path(OUT_ROOT, "logs/FUN8_score_run.log")
writeLines(capture.output(list(
  finalized = Sys.time(), scoring_status = "complete",
  formal_pan14_cells = pan_n, scored_cells = scored_n, finite_cells = finite_n,
  signatures = score_cols, sample_filter = FALSE, trajectory_sampling = FALSE,
  note = "Scores were generated by pan_reference8_01_score.R; this script only finalized documentation after a Windows filename-encoding write error."
)), run_log, useBytes = TRUE)
cat("Stage A documentation finalized.\n")
